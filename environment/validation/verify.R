options(warn=1)
packages <- c('DESeq2','edgeR','airway','Seurat','apeglm','AnnotationDbi','org.Hs.eg.db','ggplot2','ggrepel','pheatmap','dplyr')
for (p in packages) {
  library(p, character.only=TRUE)
  cat('PASS library:', p, as.character(packageVersion(p)), '\n')
}
write.csv(data.frame(package=packages, version=vapply(packages, function(p) as.character(packageVersion(p)), character(1))), 'environment/validation/r-versions.csv', row.names=FALSE)
data('airway', package='airway')
stopifnot(ncol(airway)==8, nrow(airway)>60000)
counts <- SummarizedExperiment::assay(airway)
meta <- as.data.frame(SummarizedExperiment::colData(airway))
meta$dex <- relevel(meta$dex, 'untrt')
keep <- rowSums(counts)>=10
# Actual airway model construction and edgeR dispersion estimation.
dds <- DESeqDataSetFromMatrix(counts[keep,], meta, design=~cell+dex)
dds <- estimateSizeFactors(dds)
stopifnot(all(is.finite(sizeFactors(dds))))
y <- DGEList(counts[keep,])
y <- calcNormFactors(y)
y <- estimateDisp(y, model.matrix(~cell+dex, meta))
stopifnot(is.finite(y$common.dispersion))
cat('PASS airway:', nrow(airway), 'genes;', ncol(airway), 'samples; DESeq2 size factors and edgeR dispersion\n')
set.seed(42)
s <- CreateSeuratObject(counts=counts[seq_len(1000),])
s <- NormalizeData(s, verbose=FALSE)
stopifnot(inherits(s, 'Seurat'))
cat('PASS Seurat object creation and normalization\n')
pdf('environment/validation/r-plot.pdf')
print(ggplot2::ggplot(data.frame(x=1:4,y=1:4), ggplot2::aes(x,y))+ggplot2::geom_point())
dev.off()
cat('PASS R plotting\n')
sessionInfo()
