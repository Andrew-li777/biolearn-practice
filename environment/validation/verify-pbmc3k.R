library(Seurat)
x <- Read10X('data/pbmc3k/filtered_gene_bc_matrices/hg19')
stopifnot(ncol(x)==2700, nrow(x)==32738)
s <- CreateSeuratObject(x, min.cells=3, min.features=200)
s[['percent.mt']] <- PercentageFeatureSet(s, pattern='^MT-')
s <- subset(s, subset=nFeature_RNA>200 & nFeature_RNA<2500 & percent.mt<5)
s <- NormalizeData(s, verbose=FALSE)
s <- FindVariableFeatures(s, nfeatures=2000, verbose=FALSE)
s <- ScaleData(s, features=VariableFeatures(s), verbose=FALSE)
s <- RunPCA(s, npcs=30, verbose=FALSE)
s <- FindNeighbors(s, dims=1:10, verbose=FALSE)
s <- FindClusters(s, resolution=0.5, verbose=FALSE, random.seed=42)
s <- RunUMAP(s, dims=1:10, verbose=FALSE, seed.use=42)
stopifnot(all(is.finite(Embeddings(s,'umap'))))
pdf('environment/validation/pbmc3k-seurat.pdf')
print(DimPlot(s, reduction='umap'))
dev.off()
cat('PASS PBMC3k Seurat: input=',nrow(x),'x',ncol(x),'; QC cells=',ncol(s),'; clusters=',length(unique(Idents(s))),'\n')
sessionInfo()
