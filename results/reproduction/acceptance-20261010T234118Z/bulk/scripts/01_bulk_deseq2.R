#!/usr/bin/env Rscript
options(warn=1)
suppressPackageStartupMessages({
  library(airway); library(DESeq2); library(apeglm)
  library(AnnotationDbi); library(org.Hs.eg.db)
  library(ggplot2); library(ggrepel); library(pheatmap)
})
args <- commandArgs(trailingOnly=TRUE)
outdir <- if(length(args)) args[1] else 'results/bulk'
dir.create(outdir, recursive=TRUE, showWarnings=FALSE)
path <- function(name) file.path(outdir,name)
set.seed(42)
alpha <- 0.1
data('airway', package='airway')
cts <- assay(airway,'counts')
meta <- as.data.frame(colData(airway))[,c('cell','dex'),drop=FALSE]
meta$cell <- factor(meta$cell)
meta$dex <- factor(meta$dex, levels=c('untrt','trt'))
stopifnot(identical(colnames(cts),rownames(meta)),all(cts>=0),all(cts==round(cts)),!anyNA(meta),!anyDuplicated(rownames(cts)))
design_matrix <- model.matrix(~cell+dex,meta)
stopifnot(qr(design_matrix)$rank==ncol(design_matrix))
write.csv(cts,path('airway_counts.csv'))
write.csv(meta,path('airway_coldata.csv'))
write.csv(design_matrix,path('r_design_matrix.csv'))
keep <- rowSums(cts>=10)>=3
write.csv(data.frame(gene=rownames(cts),keep=keep),path('deseq2_filter.csv'),row.names=FALSE)
cat('INPUT:',nrow(cts),'genes;',ncol(cts),'samples\nPRE_FILTER:',sum(keep),'genes\n')
dds <- DESeqDataSetFromMatrix(cts[keep,],meta,design=~cell+dex)
dds <- DESeq(dds,test='Wald',fitType='parametric',sfType='ratio',betaPrior=FALSE,minReplicatesForReplace=7,parallel=FALSE)
stopifnot('dex_trt_vs_untrt' %in% resultsNames(dds))
res <- results(dds,name='dex_trt_vs_untrt',alpha=alpha,independentFiltering=TRUE,pAdjustMethod='BH')
print(summary(res,alpha=alpha))
symbols <- mapIds(org.Hs.eg.db,keys=rownames(cts),column='SYMBOL',keytype='ENSEMBL',multiVals='first')
write.csv(data.frame(gene=names(symbols),symbol=unname(symbols)),path('gene_annotation.csv'),row.names=FALSE)
r <- as.data.frame(res)
out <- data.frame(gene=rownames(r),symbol=unname(symbols[rownames(r)]),r,check.names=FALSE)
names(out)[names(out)=='log2FoldChange'] <- 'log2FC'
out$significant <- !is.na(out$padj) & out$padj<alpha
write.csv(out,path('deseq2_results.csv'),row.names=FALSE,na='NA')
write.csv(counts(dds,normalized=TRUE),path('deseq2_normalized_counts.csv'))
write.csv(data.frame(sample=colnames(dds),size_factor=sizeFactors(dds)),path('deseq2_size_factors.csv'),row.names=FALSE)
write.csv(data.frame(gene=rownames(dds),dispersions(dds),mcols(dds)$dispGeneEst,mcols(dds)$dispFit),path('deseq2_dispersions.csv'),row.names=FALSE)
writeLines(capture.output(metadata(res)),path('deseq2_results_metadata.txt'))
writeLines(c('method=DESeq2','design=~ cell + dex','contrast=trt vs untrt','alpha=0.1','prefilter=at least 3 samples with count >= 10','normalization=median-of-ratios; sfType=ratio','test=two-sided Wald; betaPrior=FALSE; lfcThreshold=0','dispersion=parametric trend, MAP shrinkage','p_adjust=BH with independent filtering at alpha=0.1','cooks_filter=default results() cutoff','minReplicatesForReplace=7','comparison_LFC=unshrunk MLE','plot_LFC=apeglm for MA; unshrunk MLE for volcano',paste0('actual_dispersion_fit=',attr(dispersionFunction(dds),'fitType'))),path('deseq2_method.txt'))
# Use the same results object for shrinkage to preserve alpha/independent filtering.
shr <- lfcShrink(dds,coef='dex_trt_vs_untrt',res=res,type='apeglm')
shrout <- data.frame(gene=rownames(shr),log2FC_apeglm=shr$log2FoldChange,lfcSE_apeglm=shr$lfcSE,pvalue=res$pvalue,padj=res$padj)
write.csv(shrout,path('deseq2_apeglm.csv'),row.names=FALSE)
vsd <- vst(dds,blind=FALSE)
v <- assay(vsd)
write.csv(v,path('vst_expression.csv'))
pca <- plotPCA(vsd,intgroup=c('dex','cell'),returnData=TRUE)
pct <- attr(pca,'percentVar')
write.csv(pca,path('pca_scores.csv'),row.names=FALSE)
write.csv(data.frame(component=c('PC1','PC2'),variance_fraction=pct),path('pca_variance.csv'),row.names=FALSE)
p <- ggplot(pca,aes(PC1,PC2,color=dex,shape=cell))+geom_point(size=3)+geom_text_repel(aes(label=name),size=2.5,seed=42)+coord_fixed()+theme_bw()+labs(x=sprintf('PC1 (%.1f%%)',100*pct[1]),y=sprintf('PC2 (%.1f%%)',100*pct[2]),title='airway: VST PCA (top 500 variable genes)')
ggsave(path('pca.png'),p,width=8,height=6,dpi=160)
d <- as.matrix(dist(t(v)))
write.csv(d,path('sample_distance.csv'))
pheatmap(d,clustering_distance_rows=as.dist(d),clustering_distance_cols=as.dist(d),annotation_col=meta,main='Euclidean distance: VST expression',filename=path('sample_distance.png'),width=8,height=7)
png(path('ma_plot.png'),width=1200,height=850,res=160)
plotMA(shr,alpha=alpha,ylim=c(-5,5),main='airway: apeglm LFC; FDR < 0.1')
dev.off()
png(path('ma_unshrunk.png'),width=1200,height=850,res=160)
plotMA(res,alpha=alpha,ylim=c(-5,5),main='airway: unshrunk LFC; FDR < 0.1')
dev.off()
volcano <- out[is.finite(out$log2FC)&is.finite(out$pvalue),]
volcano$neglog10p <- -log10(pmax(volcano$pvalue,.Machine$double.xmin))
volcano$label <- ifelse(is.na(volcano$symbol),volcano$gene,volcano$symbol)
top <- head(volcano[order(volcano$pvalue),],10)
p <- ggplot(volcano,aes(log2FC,neglog10p,color=significant))+geom_point(size=.6,alpha=.55)+geom_text_repel(data=top,aes(label=label),size=3,seed=42,max.overlaps=Inf)+scale_color_manual(values=c('FALSE'='grey70','TRUE'='firebrick'))+theme_bw()+labs(x='Unshrunk log2 fold change (trt / untrt)',y='-log10(raw p-value)',color='FDR < 0.1',title='airway: DESeq2 volcano (no additional LFC cutoff)')
ggsave(path('volcano.png'),p,width=8,height=6,dpi=160)
ranked <- out[is.finite(out$padj),]
ranked <- ranked[order(ranked$padj,ranked$pvalue),]
top30 <- head(ranked,30)
mat <- v[top30$gene,,drop=FALSE]
write.csv(mat,path('top30_vst_expression.csv'))
write.csv(top30,path('top30_heatmap_genes.csv'),row.names=FALSE)
labels <- ifelse(is.na(top30$symbol),top30$gene,paste(top30$symbol,top30$gene,sep=' | '))
pheatmap(mat,scale='row',labels_row=labels,annotation_col=meta,main='Top 30 by DESeq2 padj: row-scaled VST',filename=path('top30_heatmap.png'),width=10,height=11)
write.csv(head(out[order(out$pvalue,na.last=TRUE),],20),path('deseq2_top20.csv'),row.names=FALSE)
write.csv(as.data.frame(installed.packages()[,c('Package','Version','Built')]),path('r_installed_packages.csv'),row.names=FALSE)
writeLines(capture.output(sessionInfo()),path('sessionInfo_deseq2.txt'))
cat('SIGNIFICANT:',sum(out$significant),'UP:',sum(out$significant & out$log2FC>0),'DOWN:',sum(out$significant & out$log2FC<0),'\n')
cat('PASS DESeq2 analysis and all figures\n')
